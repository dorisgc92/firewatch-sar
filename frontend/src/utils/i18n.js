/**
 * i18n.js
 * Zero-latency translation: everything is a plain object lookup, no network
 * calls, so switching language (or auto-detecting it on load) is instant.
 * English is always the baseline/default. The app additionally offers
 * whatever language the browser reports (navigator.language), if supported.
 */

export const SUPPORTED_LANGS = ["en", "es", "de", "fr", "pt", "it"]

export const LANG_LABELS = { en: "EN", es: "ES", de: "DE", fr: "FR", pt: "PT", it: "IT" }

export function detectLanguage() {
  if (typeof navigator === "undefined") return "en"
  const raw = (navigator.language || navigator.languages?.[0] || "en").toLowerCase()
  const code = raw.split("-")[0]
  return SUPPORTED_LANGS.includes(code) ? code : "en"
}

