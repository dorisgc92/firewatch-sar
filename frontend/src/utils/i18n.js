export const translations = { en, es, de, fr, pt, it }

export function translate(lang, key, vars) {
  let str = translations[lang]?.[key] ?? translations.en[key] ?? key
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(`{${k}}`, v)
    })
  }
  return str
}